#!/usr/bin/env python3
"""Create desktop launchers with correctly escaped, absolute Exec paths."""
import sys
from pathlib import Path


def quote(path):
    return '"' + str(path).replace('\\', '\\\\').replace('"', '\\"').replace('`', '\\`').replace('$', '\\$').replace('%', '%%') + '"'


home = Path.home()
appdir = home / '.local/share/applications'
appdir.mkdir(parents=True, exist_ok=True)
launcher = quote(home / '.local/bin/wallpapermaison-code')
text = f'''[Desktop Entry]
Type=Application
Name=Visual Studio Code (WallpaperMaison)
Exec={launcher} %F
Icon=com.visualstudio.code
Terminal=false
StartupWMClass=code
Categories=TextEditor;Development;IDE;
MimeType=text/plain;inode/directory;application/x-code-workspace;
'''
# Repair only desktop entries generated by previous versions.
for name in ('code.desktop', 'vscode.desktop'):
    target = appdir / name
    if target.exists() and 'exec "$HOME/.local/bin/code"' in target.read_text(errors='replace'):
        target.unlink()
(appdir / 'wallpapermaison-code.desktop').write_text(text, encoding='utf-8')
